#!/usr/bin/env python3
"""Lists every .bn-* class used in the public stylesheets so the CSS editor can suggest them and flag typos.
Run from the repo root after changing site.css, home.css or live.css:  python3 tools/css-editor/build-catalog.py"""
import re, pathlib, json
root = pathlib.Path(__file__).resolve().parents[2] / "BolNews.Web" / "wwwroot"
names = set()
for rel in ["css/site.css", "css/pages/home.css", "css/live.css"]:
    f = root / rel
    if f.exists():
        text = re.sub(r"/\*.*?\*/", "", f.read_text(encoding="utf-8-sig"), flags=re.S)
        names.update(re.findall(r"\.(bn-[A-Za-z0-9_-]+)", text))
# Classes written in the Razor views (some are only styled by Bootstrap or inline rules)
for view in (root.parent / "Views").rglob("*.cshtml"):
    for m in re.findall(r'class="([^"]*)"', view.read_text(encoding="utf-8-sig", errors="ignore")):
        names.update(c for c in m.split() if re.fullmatch(r"bn-[A-Za-z0-9_-]+", c))
out = root / "js" / "admin" / "css-catalog-classes.js"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("/* Generated by tools/css-editor/build-catalog.py - do not edit by hand. */\nwindow.BN_CSS_CLASSES = " + json.dumps(sorted(names)) + ";\n", encoding="utf-8")
print(len(names), "classes ->", out)
